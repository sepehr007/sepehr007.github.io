const KEY = "wt.lang";

export function getLang() {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === "fa" || saved === "en") return saved;
  } catch {}
  return "fa";
}

export function localeTag() {
  return getLang() === "fa" ? "fa-IR" : "en-US";
}

export function fmtNumber(value, options) {
  const n = Number(value);
  if (!Number.isFinite(n)) return "—";
  return n.toLocaleString(localeTag(), options || {});
}

export function fmtDate(value, options) {
  const d = value instanceof Date ? value : new Date(value);
  if (!Number.isFinite(d.getTime())) return "—";
  return d.toLocaleDateString(localeTag(), options || { year: "numeric", month: "short", day: "numeric" });
}

export function fmtTime(value) {
  const d = value instanceof Date ? value : new Date(value);
  if (!Number.isFinite(d.getTime())) return "—";
  return d.toLocaleTimeString(localeTag(), { hour: "2-digit", minute: "2-digit" });
}

export function fmtDateTime(value) {
  const d = value instanceof Date ? value : new Date(value);
  if (!Number.isFinite(d.getTime())) return "—";
  return d.toLocaleString(localeTag(), { year: "numeric", month: "short", day: "numeric", hour: "2-digit", minute: "2-digit" });
}

export function t(key, vars) {
  const dict = DICT[getLang()] || DICT.fa;
  let s = dict[key] ?? DICT.fa[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

export function applyI18n(root = document) {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "fa" ? "rtl" : "ltr";
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });
  const toggle = document.getElementById("langToggle");
  if (toggle) {
    const tag = document.getElementById("langTag");
    if (tag) tag.textContent = lang === "fa" ? "EN" : "فا";
    else toggle.textContent = lang === "fa" ? "EN" : "فا";
  }
}

export function toggleLang() {
  const next = getLang() === "fa" ? "en" : "fa";
  try { localStorage.setItem(KEY, next); } catch {}
  applyI18n();
  document.dispatchEvent(new CustomEvent("langchange", { detail: next }));
  return next;
}

export function initI18n() {
  applyI18n();
  const toggle = document.getElementById("langToggle");
  if (toggle) toggle.addEventListener("click", toggleLang);
}
